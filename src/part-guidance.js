export function roughnessAdvice(part) {
  const found = ROUGHNESS_ADVICE.find((item) => item.match.test(part ?? ""));
  return found ?? {
    why: "부품이 닿는 면은 표면이 거칠면 마모되거나 새기 쉬워 거칠기를 정해 줘야 해요.",
    how: "이 면의 표면 거칠기 기호를 넣어 주세요. 어떤 기호(w·x·y·z)를 쓸지는 문제지나 규격집에서 확인한 값으로 정해요.",
  };
}

function valueLine(label, entry) {
  return entry?.value && entry?.source
    ? `${label}: ${entry.value} (출처: ${entry.source})`
    : `${label}: 아직 확인된 값이 없어요. 문제지나 규격집에서 확인해 주세요.`;
}

// 부품 이름과 도면의 끼워맞춤 기호(예: k6)로 보여 줄 안내 줄 목록을 만들어요.
export function partGuidance(part, fit) {
  const lines = [...(PRINCIPLES[part] ?? [])];
  if (!lines.length) return [];
  if (fit && part !== "없음" && part !== "모름") {
    lines.unshift(`이 도면의 기호 ${fit}에서 소문자는 축을 뜻하고, 숫자는 공차 등급이에요.`);
    const verified = VERIFIED_PART_VALUES[part];
    lines.push(valueLine("끼워맞춤", verified?.fit), valueLine("표면 거칠기", verified?.roughness));
  }
  return lines;
}
